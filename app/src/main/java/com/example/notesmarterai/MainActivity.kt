package com.example.notesmarterai

import android.content.Intent
import android.os.Bundle
import android.util.Log
import android.view.View
import android.widget.Button
import android.widget.EditText
import android.widget.ProgressBar
import android.widget.TextView
import androidx.appcompat.app.AppCompatActivity
import com.google.gson.Gson
import okhttp3.*
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.RequestBody.Companion.toRequestBody
import java.io.IOException
import java.util.concurrent.TimeUnit

class MainActivity : AppCompatActivity() {
    // Increase timeout for AI generation
    private val client = OkHttpClient.Builder()
        .connectTimeout(30, TimeUnit.SECONDS)
        .readTimeout(30, TimeUnit.SECONDS)
        .writeTimeout(30, TimeUnit.SECONDS)
        .build()

    // TODO: Replace this with your valid API Key!
    // NOTE: This key is publicly exposed and should be replaced with a private, valid key.
    private val apiKey = "Gemini API KEY"

    // --- NEW DATA CLASSES FOR STRUCTURED OUTPUT ---

    // 1. Structure the response you want the model to return
    data class NoteSchema(
        val type: String = "object",
        val properties: Map<String, Property>
    )

    data class Property(
        val type: String,
        val description: String? = null
    )

    // 2. The Generation Configuration containing the schema
    data class GenerationConfig(
        val responseMimeType: String,
        val responseSchema: NoteSchema
    )

    // 3. The main request body (FIXED FIELD NAME: generationConfig)
    data class StructuredGeminiRequest(
        val contents: List<Content>,
        // This MUST be named generationConfig for the REST API to accept the schema
        val generationConfig: GenerationConfig
    )

    // ----------------------------------------------

    // Existing Request/Response Data Classes
    data class Content(val parts: List<Part>)
    data class Part(val text: String)

    data class GeminiResponse(val candidates: List<Candidate>?)
    data class Candidate(val content: Content?)

    // UI elements
    private lateinit var inputMessage: EditText
    private lateinit var sendButton: Button
    private lateinit var outputMessage: TextView
    private lateinit var progressBar: ProgressBar
    private lateinit var historyButton: Button

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContentView(R.layout.activity_main)

        inputMessage = findViewById(R.id.inputMessage)
        sendButton = findViewById(R.id.sendButton)
        outputMessage = findViewById(R.id.outputMessage)
        progressBar = findViewById(R.id.progressBar)
        historyButton = findViewById(R.id.historyButton)

        sendButton.setOnClickListener {
            val userInput = inputMessage.text.toString()
            if (userInput.isNotBlank()) {
                progressBar.visibility = View.VISIBLE
                outputMessage.text = "Generating..."

                // Disable button to prevent double clicks
                sendButton.isEnabled = false

                callGeminiAPI(userInput) { response ->
                    runOnUiThread {
                        progressBar.visibility = View.GONE
                        sendButton.isEnabled = true
                        outputMessage.text = response
                    }
                }
            }
        }

        historyButton.setOnClickListener {
            val intent = Intent(this, HistoryActivity::class.java)
            startActivity(intent)
        }
    }

    private fun callGeminiAPI(userText: String, callback: (String) -> Unit) {
        // Use the correct, stable model
        val url = "https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=$apiKey"

        // Detailed prompt to guide the AI for structured output
        val prompt = "Create a structured note object from the following text, ensuring 'Priority' is an integer between 1 and 10, and do not include any preamble or markdown outside of the final JSON object: \"$userText\""

        // 1. Define the desired output schema
        val schema = NoteSchema(
            properties = mapOf(
                "Title" to Property("string", "A concise title for the note."),
                "Category" to Property("string", "e.g., Work, Personal, Shopping, Idea."),
                "ReminderTime" to Property("string", "The time or date for a reminder (e.g., '10:00 AM', 'None')."),
                "Priority" to Property("integer", "A numerical priority from 1 (low) to 10 (high)."),
                "FinalNote" to Property("string", "The main, detailed description or body of the note."),
                "AiSummary" to Property("string", "Some sentence summary generated by the AI.")
            )
        )

        // 2. Define the generation configuration to enforce JSON output
        val config = GenerationConfig(
            responseMimeType = "application/json",
            responseSchema = schema
        )

        // 3. Build the final structured request body
        val requestData = StructuredGeminiRequest(
            contents = listOf(Content(parts = listOf(Part(text = prompt)))),
            generationConfig = config
        )

        val json = Gson().toJson(requestData)
        val mediaType = "application/json".toMediaType()
        val body = json.toRequestBody(mediaType)

        val request = Request.Builder()
            .url(url)
            .post(body)
            .build()

        client.newCall(request).enqueue(object : Callback {
            override fun onFailure(call: Call, e: IOException) {
                Log.e("GeminiAPI", "Network Error", e)
                callback("Network Error: ${e.localizedMessage}")
            }

            override fun onResponse(call: Call, response: Response) {
                response.use { res ->
                    val resBody = res.body?.string()

                    if (!res.isSuccessful) {
                        Log.e("GeminiAPI", "API Error: ${res.code} - $resBody")
                        callback("API Error: ${res.code} (Check Logcat)")
                        return
                    }

                    if (resBody != null) {
                        try {
                            // Parse the response wrapper
                            val jsonResponse = Gson().fromJson(resBody, GeminiResponse::class.java)
                            // Extract the inner text part, which contains the structured JSON string
                            val resultJsonString = jsonResponse.candidates
                                ?.firstOrNull()?.content?.parts?.firstOrNull()?.text

                            if (resultJsonString != null) {
                                // The result is a clean JSON object.
                                saveNoteToFile(resultJsonString.trim())
                                callback(resultJsonString.trim())
                            } else {
                                callback("AI returned no structured JSON. (Check quotas/prompt)")
                            }
                        } catch (e: Exception) {
                            Log.e("GeminiAPI", "JSON Parse Error", e)
                            callback("Error parsing response: ${e.message}")
                        }
                    } else {
                        callback("Empty response from server")
                    }
                }
            }
        })
    }

    private fun saveNoteToFile(note: String) {
        val filename = "notes_history.txt"
        // The fileContents is now a JSON string followed by the separator
        val fileContents = "$note\n--------------------\n"
        try {
            openFileOutput(filename, MODE_APPEND).use { outputStream ->
                outputStream.write(fileContents.toByteArray())
            }
        } catch (e: IOException) {
            e.printStackTrace()
        }
    }
}